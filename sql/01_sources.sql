-- Schéma source du périmètre Junior/Mid.
-- Montants en centimes et taux en pourcentages entiers.
-- Les références vers PART, PARTSUPP et REGION attendent leur intégration.

CREATE TABLE IF NOT EXISTS nation (
    N_NATIONKEY INTEGER PRIMARY KEY CHECK (N_NATIONKEY >= 0),
    N_NAME TEXT NOT NULL CHECK (length(trim(N_NAME)) > 0),
    N_REGIONKEY INTEGER NOT NULL CHECK (N_REGIONKEY >= 0),
    N_COMMENT TEXT NOT NULL
) STRICT;

CREATE TABLE IF NOT EXISTS customer (
    C_CUSTKEY INTEGER PRIMARY KEY CHECK (C_CUSTKEY > 0),
    C_NAME TEXT NOT NULL,
    C_ADDRESS TEXT NOT NULL,
    C_NATIONKEY INTEGER NOT NULL REFERENCES nation(N_NATIONKEY),
    C_PHONE TEXT NOT NULL,
    C_ACCTBAL_CENTS INTEGER NOT NULL,
    C_MKTSEGMENT TEXT NOT NULL,
    C_COMMENT TEXT NOT NULL
) STRICT;

CREATE TABLE IF NOT EXISTS orders (
    O_ORDERKEY INTEGER PRIMARY KEY CHECK (O_ORDERKEY > 0),
    O_CUSTKEY INTEGER NOT NULL REFERENCES customer(C_CUSTKEY),
    O_ORDERSTATUS TEXT NOT NULL,
    O_TOTALPRICE_CENTS INTEGER NOT NULL CHECK (O_TOTALPRICE_CENTS >= 0),
    O_ORDERDATE TEXT NOT NULL,
    O_ORDERPRIORITY TEXT NOT NULL,
    O_CLERK TEXT NOT NULL,
    O_SHIPPRIORITY INTEGER NOT NULL CHECK (O_SHIPPRIORITY >= 0),
    O_COMMENT TEXT NOT NULL
) STRICT;

CREATE TABLE IF NOT EXISTS lineitem (
    L_ORDERKEY INTEGER NOT NULL REFERENCES orders(O_ORDERKEY),
    L_PARTKEY INTEGER NOT NULL CHECK (L_PARTKEY > 0),
    L_SUPPKEY INTEGER NOT NULL CHECK (L_SUPPKEY > 0),
    L_LINENUMBER INTEGER NOT NULL CHECK (L_LINENUMBER > 0),
    L_QUANTITY INTEGER NOT NULL CHECK (L_QUANTITY > 0),
    L_EXTENDEDPRICE_CENTS INTEGER NOT NULL CHECK (L_EXTENDEDPRICE_CENTS >= 0),
    L_DISCOUNT_PERCENT INTEGER NOT NULL CHECK (L_DISCOUNT_PERCENT BETWEEN 0 AND 100),
    L_TAX_PERCENT INTEGER NOT NULL CHECK (L_TAX_PERCENT BETWEEN 0 AND 100),
    L_RETURNFLAG TEXT NOT NULL,
    L_LINESTATUS TEXT NOT NULL,
    L_SHIPDATE TEXT NOT NULL,
    L_COMMITDATE TEXT NOT NULL,
    L_RECEIPTDATE TEXT NOT NULL,
    L_SHIPINSTRUCT TEXT NOT NULL,
    L_SHIPMODE TEXT NOT NULL,
    L_COMMENT TEXT NOT NULL,
    PRIMARY KEY (L_ORDERKEY, L_LINENUMBER)
) STRICT;

CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders(O_CUSTKEY);
